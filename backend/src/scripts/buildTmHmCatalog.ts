// ---------------------------------------------------------------------------
// One-time build script — NOT run by the server.
// Sweeps every move in PokeAPI, checks whether it has ever been released as
// a real TM/HM in any mainline game (move.machines.length > 0), and writes
// the qualifying move slugs into backend/src/lib/tmHmData.ts as a static
// catalog. Re-run manually only if PokeAPI adds new TM/HM data (e.g. a new
// generation) — this is not part of the request/response cycle.
//
// Usage: npx ts-node backend/src/scripts/buildTmHmCatalog.ts
// ---------------------------------------------------------------------------

import * as fs from 'fs';
import * as path from 'path';

const CONCURRENCY = 20;

async function fetchJson(url: string): Promise<any> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Fetch failed (${res.status}): ${url}`);
  return res.json();
}

async function main() {
  console.log('Fetching move list...');
  const list = await fetchJson('https://pokeapi.co/api/v2/move?limit=1');
  const total = list.count as number;
  const allMoves = await fetchJson(`https://pokeapi.co/api/v2/move?limit=${total}&offset=0`);
  const names: string[] = allMoves.results.map((m: any) => m.name);
  console.log(`Found ${names.length} moves. Checking machine data...`);

  const qualifying: string[] = [];
  let checked = 0;

  for (let i = 0; i < names.length; i += CONCURRENCY) {
    const batch = names.slice(i, i + CONCURRENCY);
    const details = await Promise.all(
      batch.map(name => fetchJson(`https://pokeapi.co/api/v2/move/${name}`)),
    );
    for (const detail of details) {
      if ((detail.machines as any[]).length > 0) {
        qualifying.push(detail.name as string);
      }
    }
    checked += batch.length;
    console.log(`  ${checked}/${names.length} checked, ${qualifying.length} qualify so far`);
  }

  qualifying.sort();

  const outPath = path.join(__dirname, '..', 'lib', 'tmHmData.ts');
  const header = `// ---------------------------------------------------------------------------
// Static catalog of every move that has ever been released as a real TM or
// HM in a mainline Pokémon game. Generated by backend/scripts/buildTmHmCatalog.ts
// via a full sweep of PokeAPI's move data (a move qualifies if its
// \`machines\` array is non-empty in any version group). This is the single
// source of truth for "does this move actually exist as a TM/HM" — used to
// validate DM give-item requests and to power the DM's TM/HM move picker.
// Bounded, stable dataset (same shape of problem as the badge catalog) —
// re-run the script manually if PokeAPI adds a new generation's TM/HM data.
//
// Generated: ${new Date().toISOString().slice(0, 10)}
// Total qualifying moves: ${qualifying.length} / ${names.length}
// ---------------------------------------------------------------------------

export const TM_HM_MOVES: string[] = [
${qualifying.map(m => `  '${m}',`).join('\n')}
];

export function isTmHmMove(moveId: string): boolean {
  return TM_HM_MOVES.includes(moveId);
}
`;

  fs.writeFileSync(outPath, header, 'utf-8');
  console.log(`\nWrote ${qualifying.length} qualifying moves to ${outPath}`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
